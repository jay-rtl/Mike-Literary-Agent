import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const tabs = await (await fetch('http://127.0.0.1:9222/json')).json();
const ws = new WebSocket(tabs.find(tab=>tab.type==='page'&&tab.url.startsWith('http://127.0.0.1')).webSocketDebuggerUrl);
await new Promise(resolve=>ws.addEventListener('open',resolve,{once:true}));
let id=0; const pending=new Map();
ws.onmessage=event=>{const data=JSON.parse(event.data); if(data.id){pending.get(data.id)(data.result);pending.delete(data.id)}};
const cdp=(method,params={})=>new Promise(resolve=>{pending.set(++id,resolve);ws.send(JSON.stringify({id,method,params}))});
const evaluate=async expression=>(await cdp('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true})).result.value;
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
await cdp('Page.enable');await cdp('Runtime.enable');
await cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]});
await cdp('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:false});
await cdp('Page.navigate',{url:'http://127.0.0.1:4173/'});await wait(250);
assert.ok(await evaluate("document.getAnimations().some(a=>a.playState==='running')"),'Hero entrance animation runs');
await evaluate('document.fonts.ready');await wait(1000);
await evaluate("document.querySelector('.menu-toggle').click()");await wait(100);
assert.ok(await evaluate("document.querySelector('#primary-nav').getAnimations({subtree:true}).some(a=>a.playState==='running')"),'Navigation links animate');
await wait(650);
assert.ok(await evaluate("getComputedStyle(document.querySelector('.menu-icon i')).transform!=='none'"),'Menu icon transforms to close');
let shot=await cdp('Page.captureScreenshot',{format:'png'});
await writeFile('tests/review-menu-390.png',Buffer.from(shot.data,'base64'));
await cdp('Page.navigate',{url:'http://127.0.0.1:4173/for-authors.html#process'});await wait(1100);
await evaluate("document.querySelector('[data-stage=\"02\"]').click()");await wait(100);
assert.ok(await evaluate("document.querySelector('#process-02').getAnimations().some(a=>a.playState==='running')"),'Stage content transition runs');
await wait(650);
shot=await cdp('Page.captureScreenshot',{format:'png'});
await writeFile('tests/review-process-motion-390.png',Buffer.from(shot.data,'base64'));
await cdp('Page.navigate',{url:'http://127.0.0.1:4173/film-television.html#film'});await wait(1100);
assert.ok(await evaluate("document.querySelector('.screen-visual img').complete && document.querySelector('.screen-visual img').naturalWidth>0"),'Supporting image loaded');
console.log('PASS: hero entrance, menu stagger, animated close icon, stage transition, and supporting image at 390px.');
ws.close();
